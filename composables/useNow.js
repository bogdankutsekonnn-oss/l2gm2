// Общий «текущий момент» для всего, что зависит от даты (разделы главной,
// «Сегодня/Вчера», истечение платных статусов, 30-дневный фильтр).
//
// Страницы запекаются на билде, а открываются позже. Если клиент при гидрации
// посчитает разделы по своей дате, разметка разойдётся с SSR: Vue в проде не
// правит class у существующих узлов, но заменяет иконку статуса — получались
// карточки с S-иконкой без фона S-Grade и наоборот. Поэтому гидрируемся с
// моментом билда (он едет в payload через useState), а после загрузки
// переключаемся на реальное время — дальше обычный патч, всё согласовано.
let syncedOnClient = false

export const useNow = () => {
  const now = useState('render-now', () => Date.now())
  if (import.meta.client && !syncedOnClient) {
    syncedOnClient = true
    onNuxtReady(() => { now.value = Date.now() })
  }
  return now
}
